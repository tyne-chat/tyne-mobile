// Fork: writes lib/features/chat/utils/messages/generated/fork_tracking_url_rules.dart from the web
// app's TrackingUrlRules.ts in the `fluxer` submodule (tyne-chat/tyne#844), so the phone removes
// the same tracking parameters as the web and desktop apps.
//
//   dart run tool/gen_fork_tracking_url_rules.dart          # regenerate
//   dart run tool/gen_fork_tracking_url_rules.dart --check  # fail if the file is out of date
//
// Run it after the submodule moves. The test fork_tracking_url_rules_fresh_test.dart fails when the
// generated list no longer matches the submodule's rules.

import 'dart:io';

import 'fork_tracking_url_rules/ts_rules_parser.dart';

const String _outputPath =
    'lib/features/chat/utils/messages/generated/fork_tracking_url_rules.dart';

const Set<String> _ruleKeys = {
  'name',
  'match',
  'matchURL',
  'hosts',
  'removeParams',
  'removeFromPath',
  'exclude',
  'redirectParam',
  'AMP',
  'decode',
  'allowParams',
  'removeEmptyParamValues',
};
const Set<String> _ampKeys = {'regex', 'replace', 'sliceTrailing'};
const Set<String> _replaceKeys = {'text', 'with'};
const Set<String> _decodeKeys = {
  'param',
  'jsonKey',
  'encoding',
  'targetPath',
  'handler',
};

Future<void> main(List<String> args) async {
  final bool check = args.contains('--check');
  final String source = File(forkTrackingUrlRulesSourcePath).readAsStringSync();
  final String generated = await _format(
    generateRules(parseTrackingUrlRules(source)),
  );
  final File output = File(_outputPath);
  if (check) {
    if (!output.existsSync() || output.readAsStringSync() != generated) {
      stderr.writeln(
        '$_outputPath is out of date: run dart run tool/gen_fork_tracking_url_rules.dart',
      );
      exit(1);
    }
    stdout.writeln('$_outputPath is up to date.');
    return;
  }
  output.parent.createSync(recursive: true);
  output.writeAsStringSync(generated);
  stdout.writeln('Wrote $_outputPath.');
}

Future<String> _format(String code) async {
  final Directory dir = Directory.systemTemp.createTempSync(
    'fork_tracking_rules',
  );
  try {
    final File file = File('${dir.path}/rules.dart')..writeAsStringSync(code);
    final ProcessResult result = await Process.run(
      Platform.resolvedExecutable,
      ['format', '--language-version=latest', file.path],
    );
    if (result.exitCode != 0) {
      throw StateError('dart format failed: ${result.stderr}');
    }
    return file.readAsStringSync();
  } finally {
    dir.deleteSync(recursive: true);
  }
}

String generateRules(List<Map<String, Object>> rules) {
  final StringBuffer out = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by tool/gen_fork_tracking_url_rules.dart from')
    ..writeln('// $forkTrackingUrlRulesSourcePath (tyne-chat/tyne#844).')
    ..writeln(
      '// The rules are derived from tidy-url (MIT License, Copyright (c) 2021 DrKain),',
    )
    ..writeln('// as the web app notes in TrackingUrlSanitizer.LICENSE.txt.')
    ..writeln()
    ..writeln(
      "import 'package:fluxer_app/features/chat/utils/messages/fork_tracking_url_rule.dart';",
    )
    ..writeln()
    ..writeln('const List<ForkTrackingUrlRule> forkTrackingUrlRules = [');
  for (final Map<String, Object> rule in rules) {
    out.writeln('${_rule(rule)},');
  }
  out.writeln('];');
  return out.toString();
}

void _checkKeys(Map<String, Object> map, Set<String> known, String where) {
  final Iterable<String> unknown = map.keys.where((k) => !known.contains(k));
  if (unknown.isNotEmpty) {
    throw FormatException(
      'Unknown key(s) ${unknown.join(', ')} in $where: teach the generator and the sanitizer',
    );
  }
}

String _rule(Map<String, Object> rule) {
  final String name = _asString(rule['name'], 'name');
  _checkKeys(rule, _ruleKeys, 'rule $name');
  final List<String> fields = [
    'name: ${_str(name)}',
    'match: ${_regex(rule['match'], '$name match')}',
    if (rule['matchURL'] == true) 'matchUrl: true',
    if (rule['hosts'] != null)
      'hosts: ${_strings(rule['hosts'], '$name hosts')}',
    if (rule['removeParams'] != null)
      'removeParams: ${_strings(rule['removeParams'], '$name removeParams')}',
    if (rule['removeFromPath'] != null)
      'removeFromPath: ${_regexes(rule['removeFromPath'], '$name removeFromPath')}',
    if (rule['exclude'] != null)
      'exclude: ${_regexes(rule['exclude'], '$name exclude')}',
    if (rule['redirectParam'] != null)
      'redirectParam: ${_str(_asString(rule['redirectParam'], 'redirectParam'))}',
    if (rule['AMP'] != null) 'amp: ${_amp(rule['AMP']!, name)}',
    if (rule['decode'] != null) 'decode: ${_decode(rule['decode']!, name)}',
    if (rule['allowParams'] != null)
      'allowParams: ${_strings(rule['allowParams'], '$name allowParams')}',
    if (rule['removeEmptyParamValues'] == true) 'removeEmptyParamValues: true',
  ];
  return 'ForkTrackingUrlRule(${fields.join(', ')},)';
}

String _amp(Object value, String name) {
  if (value is! Map<String, Object>) {
    throw FormatException('AMP of $name is not an object');
  }
  _checkKeys(value, _ampKeys, 'AMP of $name');
  final List<String> fields = [
    if (value['regex'] != null)
      'regex: ${_regex(value['regex'], '$name AMP regex')}',
    if (value['sliceTrailing'] != null)
      'sliceTrailing: ${_str(_asString(value['sliceTrailing'], 'sliceTrailing'))}',
  ];
  final Object? replace = value['replace'];
  if (replace != null) {
    if (replace is! Map<String, Object>) {
      throw FormatException('AMP.replace of $name is not an object');
    }
    _checkKeys(replace, _replaceKeys, 'AMP.replace of $name');
    final Object? text = replace['text'];
    if (text is String) {
      fields.add('replaceText: ${_str(text)}');
    } else {
      fields.add('replacePattern: ${_regex(text, '$name AMP.replace.text')}');
    }
    if (replace['with'] != null) {
      fields.add('replaceWith: ${_str(_asString(replace['with'], 'with'))}');
    }
  }
  return 'ForkTrackingUrlAmpRule(${fields.join(', ')},)';
}

String _decode(Object value, String name) {
  if (value is! Map<String, Object>) {
    throw FormatException('decode of $name is not an object');
  }
  _checkKeys(value, _decodeKeys, 'decode of $name');
  final List<String> fields = [
    for (final String key in const ['param', 'jsonKey', 'encoding', 'handler'])
      if (value[key] != null) '$key: ${_str(_asString(value[key], key))}',
    if (value['targetPath'] == true) 'targetPath: true',
  ];
  return 'ForkTrackingUrlDecodeRule(${fields.join(', ')},)';
}

String _asString(Object? value, String what) {
  if (value is! String) {
    throw FormatException('$what is not a string: $value');
  }
  return value;
}

String _regex(Object? value, String what) {
  if (value is! TsRegExp) {
    throw FormatException('$what is not a regular expression: $value');
  }
  return value.flags.isEmpty
      ? 'ForkJsRegExp(${_str(value.source)})'
      : 'ForkJsRegExp(${_str(value.source)}, ${_str(value.flags)})';
}

String _strings(Object? value, String what) {
  if (value is! List<Object>) {
    throw FormatException('$what is not a list');
  }
  return '[${value.map((v) => _str(_asString(v, what))).join(', ')},]';
}

String _regexes(Object? value, String what) {
  if (value is! List<Object>) {
    throw FormatException('$what is not a list');
  }
  return '[${value.map((v) => _regex(v, what)).join(', ')},]';
}

/// A Dart string literal for [value]: raw when it can be, escaped otherwise.
String _str(String value) {
  if (!value.contains("'") && !value.contains('\n') && !value.contains('\r')) {
    return value.contains(r'\') || value.contains(r'$')
        ? "r'$value'"
        : "'$value'";
  }
  final String escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll(r'$', r'\$')
      .replaceAll("'", r"\'")
      .replaceAll('\n', r'\n')
      .replaceAll('\r', r'\r');
  return "'$escaped'";
}
